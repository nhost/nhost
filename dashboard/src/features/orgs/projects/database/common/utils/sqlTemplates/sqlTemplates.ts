/**
 * SQL template for fetching column metadata from a table.
 *
 * Uses positional pg-format parameters:
 *   %1$ = schema name
 *   %2$ = table name
 *
 * Returns: column info joined with PG_CATALOG data for FULL_DATA_TYPE,
 * IS_PRIMARY, IS_UNIQUE, and COLUMN_COMMENT.
 */
export const COLUMN_DEFINITION_QUERY = `
  SELECT ROW_TO_JSON(TABLE_DATA) FROM (
      SELECT *,
          PG_CATALOG.FORMAT_TYPE(
              (SELECT ATTTYPID FROM PG_ATTRIBUTE
               WHERE ATTRELID = (SELECT OID FROM PG_CLASS WHERE RELNAME = %2$L AND RELNAMESPACE = (SELECT OID FROM PG_NAMESPACE WHERE NSPNAME = %1$L))
               AND ATTNAME = COLS.COLUMN_NAME),
              (SELECT ATTTYPMOD FROM PG_ATTRIBUTE
               WHERE ATTRELID = (SELECT OID FROM PG_CLASS WHERE RELNAME = %2$L AND RELNAMESPACE = (SELECT OID FROM PG_NAMESPACE WHERE NSPNAME = %1$L))
               AND ATTNAME = COLS.COLUMN_NAME)
          ) AS FULL_DATA_TYPE,
          EXISTS (
              SELECT NSP.NSPNAME, CLS.RELNAME, ATTR.ATTNAME
              FROM PG_INDEX IND
              JOIN PG_CLASS CLS ON CLS.OID = IND.INDRELID
              JOIN PG_ATTRIBUTE ATTR ON ATTR.ATTRELID = CLS.OID AND ATTR.ATTNUM = ANY(IND.INDKEY)
              JOIN PG_NAMESPACE NSP ON NSP.OID = CLS.RELNAMESPACE
              WHERE NSPNAME = %1$L AND RELNAME = %2$L AND ATTR.ATTNAME = COLS.COLUMN_NAME AND INDISPRIMARY
          ) AS IS_PRIMARY,
          EXISTS (
              SELECT NSP.NSPNAME, CLS.RELNAME, ATTR.ATTNAME
              FROM PG_INDEX IND
              JOIN PG_CLASS CLS ON CLS.OID = IND.INDRELID
              JOIN PG_ATTRIBUTE ATTR ON ATTR.ATTRELID = CLS.OID AND ATTR.ATTNUM = ANY(IND.INDKEY)
              JOIN PG_NAMESPACE NSP ON NSP.OID = CLS.RELNAMESPACE
              WHERE NSPNAME = %1$L AND RELNAME = %2$L AND ATTR.ATTNAME = COLS.COLUMN_NAME AND INDISUNIQUE
          ) AS IS_UNIQUE,
          (
              SELECT PG_CATALOG.COL_DESCRIPTION(CLS.OID, COLS.ORDINAL_POSITION::INT)
              FROM PG_CATALOG.PG_CLASS CLS
              WHERE CLS.OID = (SELECT '%1$I.%2$I'::REGCLASS::OID) AND CLS.RELNAME = COLS.TABLE_NAME
          ) AS COLUMN_COMMENT
      FROM INFORMATION_SCHEMA.COLUMNS COLS
      WHERE TABLE_SCHEMA = %1$L AND TABLE_NAME = %2$L
  ) TABLE_DATA;
`;

/**
 * SQL template for fetching column metadata from a materialized view.
 *
 * Uses PG_ATTRIBUTE as the base since materialized views are absent
 * from INFORMATION_SCHEMA.COLUMNS.
 *
 * Uses positional pg-format parameters:
 *   %1$ = schema name
 *   %2$ = table name
 */
export const MATERIALIZED_VIEW_COLUMN_DEFINITION_QUERY = `
  SELECT ROW_TO_JSON(TABLE_DATA) FROM (
    SELECT
      ATTR.ATTNAME AS COLUMN_NAME,
      ATTR.ATTNUM AS ORDINAL_POSITION,
      CASE WHEN AD.ADBIN IS NOT NULL THEN PG_GET_EXPR(AD.ADBIN, AD.ADRELID, true) ELSE NULL END AS COLUMN_DEFAULT,
      CASE WHEN ATTR.ATTNOTNULL THEN 'NO' ELSE 'YES' END AS IS_NULLABLE,
      TYP.TYPNAME AS DATA_TYPE,
      TYP.TYPNAME AS UDT_NAME,
      NULL AS CHARACTER_MAXIMUM_LENGTH,
      NULL AS NUMERIC_PRECISION,
      NULL AS NUMERIC_SCALE,
      NULL AS DATETIME_PRECISION,
      'NO' AS IS_IDENTITY,
      PG_CATALOG.FORMAT_TYPE(ATTR.ATTTYPID, ATTR.ATTTYPMOD) AS FULL_DATA_TYPE,
      EXISTS (
        SELECT 1
        FROM PG_INDEX IND
        WHERE IND.INDRELID = CLS.OID
        AND ATTR.ATTNUM = ANY(IND.INDKEY)
        AND IND.INDISPRIMARY
      ) AS IS_PRIMARY,
      EXISTS (
        SELECT 1
        FROM PG_INDEX IND
        WHERE IND.INDRELID = CLS.OID
        AND ATTR.ATTNUM = ANY(IND.INDKEY)
        AND IND.INDISUNIQUE
        AND NOT IND.INDISPRIMARY
      ) AS IS_UNIQUE,
      PG_CATALOG.COL_DESCRIPTION(CLS.OID, ATTR.ATTNUM) AS COLUMN_COMMENT
    FROM PG_ATTRIBUTE ATTR
    JOIN PG_CLASS CLS ON CLS.OID = ATTR.ATTRELID
    JOIN PG_NAMESPACE NSP ON NSP.OID = CLS.RELNAMESPACE
    JOIN PG_TYPE TYP ON TYP.OID = ATTR.ATTTYPID
    LEFT JOIN PG_ATTRDEF AD ON AD.ADRELID = CLS.OID AND AD.ADNUM = ATTR.ATTNUM
    WHERE NSP.NSPNAME = %1$L
    AND CLS.RELNAME = %2$L
    AND ATTR.ATTNUM > 0
    AND NOT ATTR.ATTISDROPPED
  ) TABLE_DATA
  ORDER BY ORDINAL_POSITION;
`;

/**
 * SQL template for fetching complete ordered constraints and eligible
 * standalone unique indexes from a table.
 *
 * Uses positional pg-format parameters:
 *   %1$ = schema name (identifier)
 *   %2$ = table name (identifier)
 *
 * Candidate keys exclude deferrable/non-immediate and unusable indexes.
 * INCLUDE columns are omitted because only key attributes can be referenced.
 */
export const CONSTRAINT_DEFINITION_QUERY = `SELECT ROW_TO_JSON(TABLE_DATA) FROM (\
  SELECT CONSTRAINT_NAME, CONSTRAINT_TYPE, COLUMN_NAME, COLUMN_ORDINALITY, IS_REFERENCEABLE, NULLS_NOT_DISTINCT, REFERENCED_SCHEMA, REFERENCED_TABLE, REFERENCED_COLUMN_NAME, UPDATE_ACTION_CODE, DELETE_ACTION_CODE
  FROM (
    SELECT
      CON.CONNAME AS CONSTRAINT_NAME,
      CON.CONTYPE AS CONSTRAINT_TYPE,
      ATTR.ATTNAME AS COLUMN_NAME,
      AK.ORDINALITY AS COLUMN_ORDINALITY,
      (
        CON.CONTYPE = 'f'
        OR COALESCE(
          NOT CON.CONDEFERRABLE
          AND NOT CON.CONDEFERRED
          AND CONSTRAINT_INDEX.INDISUNIQUE
          AND CONSTRAINT_INDEX.INDISVALID
          AND CONSTRAINT_INDEX.INDISREADY
          AND CONSTRAINT_INDEX.INDISLIVE
          AND CONSTRAINT_INDEX.INDIMMEDIATE
          AND CONSTRAINT_INDEX.INDPRED IS NULL
          AND CONSTRAINT_INDEX.INDEXPRS IS NULL,
          FALSE
        )
      ) AS IS_REFERENCEABLE,
      COALESCE(CONSTRAINT_INDEX.INDNULLSNOTDISTINCT, FALSE) AS NULLS_NOT_DISTINCT,
      REFERENCED_NAMESPACE.NSPNAME AS REFERENCED_SCHEMA,
      REFERENCED_CLASS.RELNAME AS REFERENCED_TABLE,
      REFERENCED_ATTRIBUTE.ATTNAME AS REFERENCED_COLUMN_NAME,
      CON.CONFUPDTYPE AS UPDATE_ACTION_CODE,
      CON.CONFDELTYPE AS DELETE_ACTION_CODE
    FROM PG_CONSTRAINT CON
    CROSS JOIN LATERAL UNNEST(CON.CONKEY) WITH ORDINALITY AS AK(K, ORDINALITY)
    INNER JOIN PG_ATTRIBUTE ATTR
      ON ATTR.ATTRELID = CON.CONRELID
      AND ATTR.ATTNUM = AK.K
    LEFT JOIN PG_INDEX CONSTRAINT_INDEX
      ON CONSTRAINT_INDEX.INDEXRELID = CON.CONINDID
    LEFT JOIN LATERAL UNNEST(CON.CONFKEY) WITH ORDINALITY AS FK(K, ORDINALITY)
      ON FK.ORDINALITY = AK.ORDINALITY
    LEFT JOIN PG_CLASS REFERENCED_CLASS
      ON REFERENCED_CLASS.OID = CON.CONFRELID
    LEFT JOIN PG_NAMESPACE REFERENCED_NAMESPACE
      ON REFERENCED_NAMESPACE.OID = REFERENCED_CLASS.RELNAMESPACE
    LEFT JOIN PG_ATTRIBUTE REFERENCED_ATTRIBUTE
      ON REFERENCED_ATTRIBUTE.ATTRELID = CON.CONFRELID
      AND REFERENCED_ATTRIBUTE.ATTNUM = FK.K
    WHERE CON.CONRELID = '%1$I.%2$I'::REGCLASS
      AND CON.CONTYPE IN ('f', 'p', 'u')
      AND (
        CON.CONTYPE = 'f'
        OR AK.ORDINALITY <= CONSTRAINT_INDEX.INDNKEYATTS
      )

    UNION ALL

    SELECT
      INDEX_CLASS.RELNAME AS CONSTRAINT_NAME,
      'i'::"char" AS CONSTRAINT_TYPE,
      ATTR.ATTNAME AS COLUMN_NAME,
      AK.ORDINALITY AS COLUMN_ORDINALITY,
      TRUE AS IS_REFERENCEABLE,
      IDX.INDNULLSNOTDISTINCT AS NULLS_NOT_DISTINCT,
      NULL::TEXT AS REFERENCED_SCHEMA,
      NULL::TEXT AS REFERENCED_TABLE,
      NULL::TEXT AS REFERENCED_COLUMN_NAME,
      NULL::"char" AS UPDATE_ACTION_CODE,
      NULL::"char" AS DELETE_ACTION_CODE
    FROM PG_INDEX IDX
    INNER JOIN PG_CLASS INDEX_CLASS
      ON INDEX_CLASS.OID = IDX.INDEXRELID
    CROSS JOIN LATERAL UNNEST(IDX.INDKEY) WITH ORDINALITY AS AK(K, ORDINALITY)
    INNER JOIN PG_ATTRIBUTE ATTR
      ON ATTR.ATTRELID = IDX.INDRELID
      AND ATTR.ATTNUM = AK.K
      AND ATTR.ATTNUM > 0
    WHERE IDX.INDRELID = '%1$I.%2$I'::REGCLASS
      AND AK.ORDINALITY <= IDX.INDNKEYATTS
      AND IDX.INDISUNIQUE
      AND IDX.INDISVALID
      AND IDX.INDISREADY
      AND IDX.INDISLIVE
      AND IDX.INDIMMEDIATE
      AND NOT IDX.INDISPRIMARY
      AND IDX.INDPRED IS NULL
      AND IDX.INDEXPRS IS NULL
      AND NOT EXISTS (
        SELECT 1
        FROM PG_CONSTRAINT CON
        WHERE CON.CONINDID = IDX.INDEXRELID
      )
  ) CONSTRAINT_AND_INDEX_DATA
  ORDER BY CONSTRAINT_TYPE, CONSTRAINT_NAME, COLUMN_ORDINALITY
) TABLE_DATA`;
