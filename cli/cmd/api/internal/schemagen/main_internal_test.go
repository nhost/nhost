func writeCredentials(t *testing.T) {
	t.Helper()

	path := filepath.Join(os.Getenv("XDG_STATE_HOME"), "nhost", "auth.json")
	if err := os.MkdirAll(filepath.Dir(path), 0o700); err != nil {
		t.Fatal(err)
	}

	if err := os.WriteFile(
		path,
		[]byte(`{"oauth2RefreshToken":"synthetic-refresh"}`),
		0o600,
	); err != nil {
		t.Fatal(err)
	}
}

type authServer struct {
	server      *httptest.Server
	patRequests atomic.Int32
}

func newAuthServer(t *testing.T, fail bool) *authServer {
	t.Helper()

	s := &authServer{}
	s.server = httptest.NewServer(http.HandlerFunc(func(w http.ResponseWriter, r *http.Request) {
		w.Header().Set("Content-Type", "application/json")

		switch r.URL.Path {
		case "/.well-known/oauth-authorization-server":
			writeBody(t, w, fmt.Sprintf(`{"token_endpoint":%q}`, s.server.URL+"/oauth2/token"))
		case "/oauth2/token":
			if fail {
				w.WriteHeader(http.StatusBadRequest)
				writeBody(t, w, `{"error":"invalid_grant"}`)

				return
			}

			writeBody(
				t,
				w,
				`{"access_token":"synthetic-access","refresh_token":"synthetic-refresh","expires_in":3600,"token_type":"Bearer"}`,
			)
		case "/signin/pat":
			var payload struct {
				PersonalAccessToken string `json:"personalAccessToken"`
			}
			if err := json.NewDecoder(r.Body).Decode(&payload); err != nil {
				t.Error(err)
				return
			}

			if payload.PersonalAccessToken != "synthetic-pat" {
				t.Error("unexpected PAT sign-in payload")
			}

			s.patRequests.Add(1)

			writeBody(
				t,
				w,
				`{"session":{"accessToken":"synthetic-access","accessTokenExpiresIn":3600,"refreshToken":"synthetic-refresh"}}`,
			)
		default:
			t.Errorf("unexpected auth endpoint: %s", r.URL.Path)
			http.NotFound(w, r)
		}
	}))
	t.Cleanup(s.server.Close)

	return s
}

func newGraphQLServer(
	t *testing.T,
	status int,
	stall bool,
) (*httptest.Server, *atomic.Int32) {
	t.Helper()

	requests := new(atomic.Int32)
	server := httptest.NewServer(http.HandlerFunc(func(w http.ResponseWriter, r *http.Request) {
		requests.Add(1)

		if r.Header.Get("Authorization") != "Bearer synthetic-access" ||
			r.Header.Get("X-Hasura-Role") != "user" {
			t.Error("introspection must carry bearer authentication and the user role")
		}

		// Introspection is sent without retries, so stalling it ends the run at the
		// deadline. Stalling PAT sign-in instead would add the auth client's retry delays.
		if stall {
			// The server cancels r.Context() on disconnect only after the body is read.
			if _, err := io.Copy(io.Discard, r.Body); err != nil {
				t.Error(err)
			}

			select {
			case <-r.Context().Done():
			case <-time.After(2 * time.Second):
			}

			return
		}

		w.Header().Set("Content-Type", "application/json")
		w.WriteHeader(status)
		writeBody(t, w, simpleIntrospection)
	}))
	t.Cleanup(server.Close)

	return server, requests
}

func TestAction(t *testing.T) {
	tests := []struct {
		name         string
		pat          bool
		authFailure  bool
		stall        bool
		status       int
		wantErr      string
		wantRequests int32
	}{
		{name: "OAuth session success", status: http.StatusOK, wantRequests: 1},
		{name: "PAT success", pat: true, status: http.StatusOK, wantRequests: 1},
		{
			name:         "HTTP 500 preserves output",
			status:       http.StatusInternalServerError,
			wantErr:      "remote schema returned status",
			wantRequests: 1,
		},
		{
			name:        "interceptor failure preserves output",
			authFailure: true,
			status:      http.StatusOK,
			wantErr:     "authenticating introspection request",
		},
		{
			name:         "deadline preserves output",
			pat:          true,
			stall:        true,
			status:       http.StatusOK,
			wantErr:      "sending introspection request",
			wantRequests: 1,
		},
	}
	for _, tt := range tests {
		t.Run(tt.name, func(t *testing.T) {
			t.Setenv("XDG_STATE_HOME", isolateEnv(t))
			writeCredentials(t)
			auth := newAuthServer(t, tt.authFailure)

			graphql, requests := newGraphQLServer(t, tt.status, tt.stall)
			t.Setenv("NHOST_CLI_AUTH_URL", auth.server.URL)
			t.Setenv("NHOST_CLI_GRAPHQL_URL", graphql.URL)

			if tt.pat {
				t.Setenv("NHOST_PAT", "synthetic-pat")
			}

			output := filepath.Join(t.TempDir(), "schema.graphql")

			const original = "existing snapshot\n"
			if err := os.WriteFile(output, []byte(original), 0o600); err != nil {
				t.Fatal(err)
			}

			cmd, err := command()
			if err != nil {
				t.Fatal(err)
			}

			cmd.Writer, cmd.ErrWriter = io.Discard, io.Discard

			args := []string{"schemagen", "--output", output}
			if tt.stall {
				args = append(args, "--timeout", "500ms")
			}

			err = cmd.Run(t.Context(), args)

			want := simpleSDL
			if tt.wantErr != "" {
				want = original

				if err == nil || !strings.Contains(err.Error(), tt.wantErr) {
					t.Fatalf("error = %v, want %q", err, tt.wantErr)
				}
			} else if err != nil {
				t.Fatal(err)
			}

			if tt.stall &&
				(!errors.Is(err, context.DeadlineExceeded) || auth.patRequests.Load() != 1) {
				t.Fatalf(
					"introspection must hit the shared deadline after PAT sign-in: requests=%d, error=%v",
					auth.patRequests.Load(),
					err,
				)
			}

			if got := requests.Load(); got != tt.wantRequests {
				t.Errorf("GraphQL requests = %d, want %d", got, tt.wantRequests)
			}

			checkOutput(t, output, want)
		})
	}
}

func checkOutput(t *testing.T, output, want string) {
	t.Helper()

	data, err := os.ReadFile(output)
	if err != nil {
		t.Fatal(err)
	}

	if string(data) != want {
		t.Errorf("output = %q, want %q", data, want)
	}

	entries, err := os.ReadDir(filepath.Dir(output))
	if err != nil {
		t.Fatal(err)
	}

	if len(entries) != 1 {
		t.Errorf("temporary files left in output directory: %v", entries)
	}
}

func TestCommandRequiresOutput(t *testing.T) {
	t.Setenv("XDG_STATE_HOME", isolateEnv(t))

	cmd, err := command()
	if err != nil {
		t.Fatal(err)
	}

	cmd.Writer, cmd.ErrWriter = io.Discard, io.Discard
	if err := cmd.Run(
		t.Context(),
		[]string{"schemagen"},
	); err == nil ||
		!strings.Contains(err.Error(), "output") {
		t.Fatalf("error = %v, want required output flag error", err)
	}
}
