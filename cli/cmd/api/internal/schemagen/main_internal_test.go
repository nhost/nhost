const simpleIntrospection = `{"data":{"__schema":{
  "queryType":{"name":"query_root"},
  "mutationType":{"name":"mutation_root"},
  "types":[
    {"kind":"OBJECT","name":"query_root","fields":[
      {"name":"apps","type":{"kind":"SCALAR","name":"String"}}
    ]},
    {"kind":"OBJECT","name":"mutation_root","fields":[
      {"name":"updateApp","type":{"kind":"SCALAR","name":"Boolean"}}
    ]}
  ]
}}}`

const simpleSDL = `# Code generated by cli/cmd/api/internal/schemagen. DO NOT EDIT.
schema {
  query: query_root
  mutation: mutation_root
}
type mutation_root {
  updateApp: Boolean
}
type query_root {
  apps: String
}
`

func isolateEnv(t *testing.T) string {
	t.Helper()

	for _, entry := range os.Environ() {
		name, _, _ := strings.Cut(entry, "=")
		if name == "NHOST_PAT" || strings.HasPrefix(name, "NHOST_CLI_") {
			t.Setenv(name, "")

			if err := os.Unsetenv(name); err != nil {
				t.Fatal(err)
			}
		}
	}

	t.Setenv("HOME", t.TempDir())

	return t.TempDir()
}

func serveJSON(t *testing.T, status int, body string) *httptest.Server {
	t.Helper()

	server := httptest.NewServer(http.HandlerFunc(func(w http.ResponseWriter, r *http.Request) {
		if r.Header.Get("X-Hasura-Role") != "user" {
			t.Error("introspection request must pin the user role")
		}

		w.Header().Set("Content-Type", "application/json")
		w.WriteHeader(status)
		writeBody(t, w, body)
	}))
	t.Cleanup(server.Close)

	return server
}

func writeBody(t *testing.T, w io.Writer, body string) {
	t.Helper()

	if _, err := io.WriteString(w, body); err != nil {
		t.Error(err)
	}
}

