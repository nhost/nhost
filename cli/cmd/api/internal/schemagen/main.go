// Command schemagen generates a validated Cloud GraphQL SDL snapshot.
package main

import (
	"context"
	"errors"
	"fmt"
	"net/http"
	"os"
	"path/filepath"
	"time"

	"github.com/nhost/nhost/cli/clienv"
	"github.com/nhost/nhost/cli/cmd/api/internal/sdl"
	"github.com/nhost/nhost/services/constellation/connector/remoteschema"
	"github.com/urfave/cli/v3"
	"github.com/vektah/gqlparser/v2"
	"github.com/vektah/gqlparser/v2/ast"
)

const (
	generatedHeader = "# Code generated by cli/cmd/api/internal/schemagen. DO NOT EDIT.\n"
	defaultTimeout  = 2 * time.Minute
	authHint        = "check `nhost login` or NHOST_PAT, the X-Hasura-Role: user pin, " +
		"and the NHOST_CLI_GRAPHQL_URL override"
)

var (
	errQueryRoot = errors.New(
		"query root is missing, empty, or contains only no_queries_available",
	)
	errMutationRoot = errors.New("mutation root is missing")
)

func main() {
	cmd, err := command()
	if err == nil {
		err = cmd.Run(context.Background(), os.Args)
	}

	if err != nil {
		fmt.Fprintln(os.Stderr, err)
		os.Exit(1)
	}
}

func command() (*cli.Command, error) {
	flags, err := clienv.Flags()
	if err != nil {
		return nil, fmt.Errorf("building environment flags: %w", err)
	}

	flags = append(flags,
		&cli.StringFlag{ //nolint:exhaustruct
			Name: "output", Required: true, Usage: "Output SDL file",
		},
		&cli.DurationFlag{ //nolint:exhaustruct
			Name:  "timeout",
			Value: defaultTimeout,
			Usage: "Deadline for authentication and introspection",
		},
	)

	return &cli.Command{ //nolint:exhaustruct
		Name: "schemagen", Usage: "Generate the Cloud user-role schema snapshot",
		Flags: flags, Action: action,
		// Let main report all failures once, with the same exit status.
		ExitErrHandler: func(context.Context, *cli.Command, error) {},
	}, nil
}

func action(ctx context.Context, cmd *cli.Command) error {
	ctx, cancel := context.WithTimeout(ctx, cmd.Duration("timeout"))
	defer cancel()

	ce := clienv.FromCLI(cmd)

	interceptor, err := ce.NewCloudInterceptor(ctx)
	if err != nil {
		return fmt.Errorf("creating Cloud interceptor: %w", err)
	}

	data, err := generate(ctx, ce.GraphqlURL(), interceptedDoer{intercept: interceptor})
	if err != nil {
		return fmt.Errorf("generating Cloud snapshot: %w", err)
	}

	return writeSnapshot(cmd.String("output"), data)
}

type interceptedDoer struct {
	intercept func(context.Context, *http.Request) error
}

func (d interceptedDoer) Do(req *http.Request) (*http.Response, error) {
	if err := d.intercept(req.Context(), req); err != nil {
		return nil, fmt.Errorf("authenticating introspection request: %w", err)
	}

	//nolint:gosec // G704: the URL is the operator's own --graphql-url, not remote input
	response, err := http.DefaultClient.Do(req)
	if err != nil {
		return nil, fmt.Errorf("sending introspection request: %w", err)
	}

	return response, nil
}

func generate(ctx context.Context, url string, doer remoteschema.HTTPDoer) ([]byte, error) {
	schema, err := remoteschema.Introspect(
		ctx,
		url,
		map[string]string{"X-Hasura-Role": "user"},
		doer,
	)
	if err != nil {
		if errors.Is(err, remoteschema.ErrRemoteStatus) ||
			errors.Is(err, remoteschema.ErrIntrospectionResponse) {
			return nil, fmt.Errorf("introspecting Cloud schema (%s): %w", authHint, err)
		}

		return nil, fmt.Errorf("introspecting Cloud schema: %w", err)
	}

	doc := schema.ToAST()
	if schema.QueryType == nil || !hasQueries(doc.Definitions.ForName(*schema.QueryType)) {
		return nil, errQueryRoot
	}

	if schema.MutationType == nil || doc.Definitions.ForName(*schema.MutationType) == nil {
		return nil, errMutationRoot
	}

	preserveDefaults(doc)

	validated, err := gqlparser.LoadSchema(
		&ast.Source{
			Name:    "introspection",
			Input:   string(sdl.FormatSchemaDocument(doc)),
			BuiltIn: false,
		},
	)
	if err != nil {
		return nil, fmt.Errorf("validating introspected SDL: %w", err)
	}

	result := append([]byte(generatedHeader), sdl.FormatSchema(validated)...)
	if _, err := gqlparser.LoadSchema(
		&ast.Source{Name: "snapshot", Input: string(result), BuiltIn: false},
	); err != nil {
		return nil, fmt.Errorf("validating canonical SDL: %w", err)
	}

	return result, nil
}

func hasQueries(root *ast.Definition) bool {
	if root != nil {
		for _, field := range root.Fields {
			if field.Name != "no_queries_available" {
				return true
			}
		}
	}

	return false
}

func preserveDefaults(doc *ast.SchemaDocument) {
	for _, def := range doc.Definitions {
		for _, field := range def.Fields {
			preserveDefault(field.DefaultValue)
			preserveArgumentDefaults(field.Arguments)
		}
	}

	for _, directive := range doc.Directives {
		preserveArgumentDefaults(directive.Arguments)
	}
}

func preserveArgumentDefaults(args ast.ArgumentDefinitionList) {
	for _, arg := range args {
		preserveDefault(arg.DefaultValue)
	}
}

func preserveDefault(value *ast.Value) {
	if value != nil {
		// ToAST keeps raw introspection literals, but does not decode strings or
		// populate list/object children. EnumValue prints Raw verbatim; the next
		// LoadSchema validates and reconstructs the proper value tree and kind.
		value.Kind = ast.EnumValue
	}
}

func writeSnapshot(output string, data []byte) (retErr error) {
	file, err := os.CreateTemp(filepath.Dir(output), ".schemagen-*")
	if err != nil {
		return fmt.Errorf("creating snapshot temp file: %w", err)
	}

	defer func() {
		if err := os.Remove(file.Name()); err != nil && !errors.Is(err, os.ErrNotExist) {
			retErr = errors.Join(retErr, fmt.Errorf("removing snapshot temp file: %w", err))
		}
	}()

	_, writeErr := file.Write(data)

	closeErr := file.Close()
	if err := errors.Join(writeErr, closeErr); err != nil {
		return fmt.Errorf("writing snapshot temp file: %w", err)
	}

	if err := os.Rename(file.Name(), output); err != nil {
		return fmt.Errorf("replacing snapshot: %w", err)
	}

	return nil
}
