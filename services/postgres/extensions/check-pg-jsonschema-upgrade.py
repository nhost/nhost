from __future__ import annotations

import argparse
import difflib
import re
from collections import Counter
from pathlib import Path

_BEGIN_BLOCK = "/* <begin connected objects> */"
_END_BLOCK = "/* </end connected objects> */"
_GENERATED_HEADER = "This file is auto generated by pgrx."
_EXISTING_WRAPPERS = frozenset(
    {
        "json_matches_schema_wrapper",
        "jsonb_matches_schema_wrapper",
        "jsonschema_is_valid_wrapper",
        "jsonschema_validation_errors_wrapper",
    }
)
_WRAPPER_PATTERN = re.compile(r"AS\s+'MODULE_PATHNAME',\s+'([^']+)';")
_COMMENT_PATTERN = re.compile(r"/\*.*?\*/", re.DOTALL)


def _connected_objects(path: Path) -> tuple[list[str], str]:
    blocks: list[str] = []
    outside: list[str] = []
    current: list[str] | None = None

    for line in path.read_text(encoding="utf-8").splitlines():
        if line == _BEGIN_BLOCK:
            if current is not None:
                raise ValueError(f"{path}: nested connected-object block")
            current = [line]
        elif line == _END_BLOCK:
            if current is None:
                raise ValueError(f"{path}: unmatched connected-object block end")
            current.append(line)
            blocks.append("\n".join(current))
            current = None
        elif current is None:
            outside.append(line)
        else:
            current.append(line)

    if current is not None:
        raise ValueError(f"{path}: unterminated connected-object block")

    return blocks, "\n".join(outside)


def _upgrade_objects(install_path: Path) -> list[str]:
    install_blocks, outside = _connected_objects(install_path)
    if outside.strip():
        raise ValueError(
            f"{install_path}: unexpected content outside connected-object blocks"
        )

    existing_wrappers: set[str] = set()
    header_blocks = 0
    upgrade_blocks: list[str] = []

    for block in install_blocks:
        if _GENERATED_HEADER in block:
            header_blocks += 1
            continue

        wrappers = set(_WRAPPER_PATTERN.findall(block))
        inherited = wrappers & _EXISTING_WRAPPERS
        if inherited:
            if len(inherited) != 1 or wrappers != inherited:
                raise ValueError(
                    f"{install_path}: an existing function shares a connected-object "
                    "block with another function"
                )
            existing_wrappers.update(inherited)
            continue

        upgrade_blocks.append(block)

    if header_blocks != 1:
        raise ValueError(f"{install_path}: expected one pgrx-generated header block")
    if existing_wrappers != _EXISTING_WRAPPERS:
        missing = ", ".join(sorted(_EXISTING_WRAPPERS - existing_wrappers))
        raise ValueError(f"{install_path}: missing existing 0.3.3 functions: {missing}")

    return upgrade_blocks


def _verify(install_path: Path, upgrade_path: Path) -> None:
    expected = _upgrade_objects(install_path)
    actual, outside = _connected_objects(upgrade_path)
    if _COMMENT_PATTERN.sub("", outside).strip():
        raise ValueError(
            f"{upgrade_path}: unexpected SQL outside connected-object blocks"
        )

    if Counter(actual) == Counter(expected):
        return

    expected_text = "\n\n".join(sorted(expected))
    actual_text = "\n\n".join(sorted(actual))
    difference = "\n".join(
        difflib.unified_diff(
            actual_text.splitlines(),
            expected_text.splitlines(),
            fromfile=str(upgrade_path),
            tofile=f"{install_path} minus pg_jsonschema 0.3.3 objects",
            lineterm="",
        )
    )
    raise ValueError(f"pg_jsonschema upgrade script is out of date:\n{difference}")


def main() -> None:
    parser = argparse.ArgumentParser(
        description="Check the pg_jsonschema upgrade script against generated install SQL."
    )
    parser.add_argument("install_script", type=Path)
    parser.add_argument("upgrade_script", type=Path)
    args = parser.parse_args()

    try:
        _verify(args.install_script, args.upgrade_script)
    except (OSError, ValueError) as error:
        parser.exit(1, f"{error}\n")


if __name__ == "__main__":
    main()
