"""Regression tests for the pgrx-generated pg_jsonschema upgrade checker."""

import subprocess
import sys
import tempfile
import unittest
from pathlib import Path

CHECKER = (
    Path(__file__).resolve().parents[1] / "extensions/check-pg-jsonschema-upgrade.py"
)
FUNCTIONS = {
    "json_matches_schema": ('"schema" json, "instance" json', "bool"),
    "jsonb_matches_schema": ('"schema" json, "instance" jsonb', "bool"),
    "jsonschema_is_valid": ('"schema" json', "bool"),
    "jsonschema_validation_errors": ('"schema" json, "instance" json', "TEXT[]"),
}


def connected(sql):
    return f"/* <begin connected objects> */\n{sql}\n/* </end connected objects> */"


def install_sql():
    blocks = [connected("/* This file is auto generated by pgrx. */")]
    for name, (arguments, result) in FUNCTIONS.items():
        blocks.append(
            connected(
                f"-- src/lib.rs:10\n-- pg_jsonschema::{name}\n"
                f'CREATE  FUNCTION "{name}"({arguments} /* Json */) '
                f"RETURNS {result} /* Rust */\n"
                "IMMUTABLE STRICT PARALLEL SAFE\nLANGUAGE c /* Rust */\n"
                f"AS 'MODULE_PATHNAME', '{name}_wrapper';"
            )
        )
    blocks.append(
        connected(
            'CREATE FUNCTION "new_function"() RETURNS bool LANGUAGE c '
            "AS 'MODULE_PATHNAME', 'new_function_wrapper';"
        )
    )
    return "\n".join(blocks)


UPGRADE = connected(
    'CREATE FUNCTION "new_function"() RETURNS bool LANGUAGE c '
    "AS 'MODULE_PATHNAME', 'new_function_wrapper';"
)


class UpgradeCheckerTests(unittest.TestCase):
    def check(self, install, upgrade=UPGRADE):
        with tempfile.TemporaryDirectory() as directory:
            install_path = Path(directory) / "pg_jsonschema--0.3.4.sql"
            upgrade_path = Path(directory) / "pg_jsonschema--0.3.3--0.3.4.sql"
            install_path.write_text(install, encoding="utf-8")
            upgrade_path.write_text(upgrade, encoding="utf-8")
            return subprocess.run(
                [sys.executable, str(CHECKER), str(install_path), str(upgrade_path)],
                capture_output=True,
                text=True,
                check=False,
            )

    def test_comment_and_locator_changes_are_ignored(self):
        install = install_sql().replace("/* Json */", "/* pgrx::datum::json::Json */")
        install = install.replace("-- src/lib.rs:10", "-- src/lib.rs:42")
        self.assertEqual(self.check(install).returncode, 0)

    def test_signature_drift_is_rejected_for_each_inherited_function(self):
        for name, (arguments, _) in FUNCTIONS.items():
            with self.subTest(name=name):
                original = f'"{name}"({arguments} /* Json */)'
                changed = original.replace('"schema" json', '"schema" jsonb', 1)
                result = self.check(install_sql().replace(original, changed))
                self.assertEqual(result.returncode, 1)
                self.assertIn(f"{name}_wrapper differs", result.stderr)
                self.assertIn("CREATE OR REPLACE FUNCTION", result.stderr)

    def test_volatility_drift_is_rejected(self):
        result = self.check(install_sql().replace("IMMUTABLE", "STABLE", 1))
        self.assertEqual(result.returncode, 1)
        self.assertIn("json_matches_schema_wrapper differs", result.stderr)

    def test_duplicate_inherited_block_is_rejected(self):
        blocks = install_sql().split("/* <begin connected objects> */")
        duplicate = "/* <begin connected objects> */" + blocks[2]
        result = self.check(install_sql() + "\n" + duplicate)
        self.assertEqual(result.returncode, 1)
        self.assertIn("duplicate 0.3.3 function", result.stderr)

    def test_new_object_drift_is_still_rejected(self):
        result = self.check(install_sql(), "")
        self.assertEqual(result.returncode, 1)
        self.assertIn("upgrade script is out of date", result.stderr)


if __name__ == "__main__":
    unittest.main()
