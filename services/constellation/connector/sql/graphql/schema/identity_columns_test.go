// Use real introspection: a hand-built IsGenerated flag would miss the
// distinction between pg_attribute.attgenerated and attidentity = 'a'.
func TestGenerateForRole_IdentityColumns(t *testing.T) {
	t.Parallel()

	pool := testdb.NewPostgres(t, `
CREATE SCHEMA support;
CREATE TABLE support.tickets (
    id integer PRIMARY KEY,
    ticket_number bigint GENERATED ALWAYS AS IDENTITY UNIQUE,
    default_number bigint GENERATED BY DEFAULT AS IDENTITY,
    serial_number bigserial,
    computed_number integer GENERATED ALWAYS AS (version + 1) STORED,
    version integer NOT NULL DEFAULT 1
);`)

	pgPool, err := postgres.Open(t.Context(), pool.Config().ConnConfig.ConnString())
	if err != nil {
		t.Fatalf("open pool: %v", err)
	}

	pg := postgres.NewClient(pgPool)
	t.Cleanup(pg.Close)

	columns := []string{
		"id",
		"ticket_number",
		"default_number",
		"serial_number",
		"computed_number",
		"version",
	}
	md := &metadata.DatabaseMetadata{
		Name: "default",
		Tables: []metadata.TableMetadata{{
			Table: metadata.TableSource{Schema: "support", Name: "tickets"},
			Configuration: metadata.TableConfiguration{
				CustomName: "supportTickets",
				ColumnConfig: map[string]metadata.ColumnConfig{
					"ticket_number":   {CustomName: "number"},
					"default_number":  {CustomName: "defaultNumber"},
					"serial_number":   {CustomName: "serialNumber"},
					"computed_number": {CustomName: "computedNumber"},
				},
			},
			SelectPermissions: []metadata.SelectPermission{{
				Role: "writer",
				Permission: metadata.SelectPermissionConfig{
					Columns: columns, AllowAggregations: true,
				},
			}},
			InsertPermissions: []metadata.InsertPermission{{
				Role: "writer", Permission: metadata.InsertPermissionConfig{Columns: columns},
			}},
			UpdatePermissions: []metadata.UpdatePermission{{
				Role: "writer", Permission: metadata.UpdatePermissionConfig{Columns: columns},
			}},
		}},
	}

	objects, err := pg.Introspect(t.Context(), md)
	if err != nil {
		t.Fatalf("introspect: %v", err)
	}

	caps := schema.NewCapabilities(schema.KindPostgres, dialect.NewPostgresDialect())
	tests := []struct {
		name     string
		writable bool
	}{
		{name: "number", writable: false},
		{name: "defaultNumber", writable: true},
		{name: "serialNumber", writable: true},
		{name: "computedNumber", writable: false},
		{name: "version", writable: true},
	}

	for _, role := range []string{"admin", "writer"} {
		t.Run(role, func(t *testing.T) {
			t.Parallel()

			sdl := generateSchemaSDL(t, objects, md, caps, role)

			sch, err := gqlparser.LoadSchema(&ast.Source{Input: sdl})
			if err != nil {
				t.Fatalf("generated invalid schema: %v", err)
			}

			for _, tt := range tests {
				t.Run(tt.name, func(t *testing.T) {
					t.Parallel()

					assertIdentityColumnSchema(t, sch, tt.name, tt.writable)
				})
			}
		})
	}
}

func assertIdentityColumnSchema(t *testing.T, sch *ast.Schema, name string, writable bool) {
	t.Helper()

	for _, suffix := range []string{"_insert_input", "_set_input", "_inc_input"} {
		def := sch.Types["supportTickets"+suffix]
		if def == nil {
			t.Fatalf("missing type supportTickets%s", suffix)
		}

		if got := def.Fields.ForName(name) != nil; got != writable {
			t.Errorf("supportTickets%s.%s present = %v, want %v", suffix, name, got, writable)
		}
	}

	updateColumns := sch.Types["supportTickets_update_column"]
	if updateColumns == nil {
		t.Fatal("missing update column enum")
	}

	if got := updateColumns.EnumValues.ForName(name) != nil; got != writable {
		t.Errorf("update column %s present = %v, want %v", name, got, writable)
	}

	// Read surfaces must retain generated values, including stream
	// cursors and filters that are inputs but do not write columns.
	for _, suffix := range []string{"", "_bool_exp", "_order_by", "_stream_cursor_value_input", "_max_fields", "_sum_fields"} {
		def := sch.Types["supportTickets"+suffix]
		if def == nil || def.Fields.ForName(name) == nil {
			t.Errorf("missing readable field supportTickets%s.%s", suffix, name)
		}
	}
}
