type insertRelationship struct {
	source string
	target string
	array  bool
}

// Reuse one isolated database and pool for the whole relationship matrix.
//
//nolint:paralleltest
func TestGenerateForRole_EmptyInsertInputs(t *testing.T) {
	pool := testdb.NewPostgres(t, `
CREATE TABLE ids_a (id bigint GENERATED ALWAYS AS IDENTITY PRIMARY KEY);
CREATE TABLE ids_b (id bigint GENERATED ALWAYS AS IDENTITY PRIMARY KEY);
CREATE TABLE ids_c (id bigint GENERATED ALWAYS AS IDENTITY PRIMARY KEY);
CREATE TABLE likes (id bigint GENERATED ALWAYS AS IDENTITY PRIMARY KEY, user_id text NOT NULL);
CREATE TABLE writable (id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, payload text);
CREATE VIEW readonly_ids AS SELECT id FROM ids_a UNION ALL SELECT id FROM ids_b;`)

	connString := pool.Config().ConnConfig.ConnString()
	pool.Close()

	pgPool, err := postgres.Open(t.Context(), connString)
	if err != nil {
		t.Fatalf("open pool: %v", err)
	}

	pg := postgres.NewClient(pgPool)
	t.Cleanup(pg.Close)

	objects, err := pg.Introspect(t.Context(), emptyInsertMetadata(nil))
	if err != nil {
		t.Fatalf("introspect: %v", err)
	}

	tests := []struct {
		name          string
		relationships []insertRelationship
		denyInsert    string
		denySelect    string
		presetOnly    bool
	}{
		{name: "isolated identity and identity plus preset"},
		{name: "preset only permission", presetOnly: true},
		{
			name: "writable parent references empty targets",
			relationships: []insertRelationship{
				{source: "writable", target: "ids_a"},
				{source: "writable", target: "ids_b", array: true},
			},
		},
		{
			name: "relationship fields keep a transitive chain insertable",
			relationships: []insertRelationship{
				{source: "ids_a", target: "ids_b"},
				{source: "ids_b", target: "writable", array: true},
			},
		},
		{
			name: "empty targets remain insertable through a chain",
			relationships: []insertRelationship{
				{source: "ids_a", target: "ids_b"},
				{source: "ids_b", target: "ids_c", array: true},
			},
		},
		{
			name: "relationship only cycle remains valid",
			relationships: []insertRelationship{
				{source: "ids_a", target: "ids_b"},
				{source: "ids_b", target: "ids_a", array: true},
			},
		},
		{
			name:          "self relationship remains valid",
			relationships: []insertRelationship{{source: "ids_a", target: "ids_a"}},
		},
		{
			name:          "read only view is not insertable",
			relationships: []insertRelationship{{source: "ids_a", target: "readonly_ids"}},
		},
		{
			name:          "target requires insert permission",
			relationships: []insertRelationship{{source: "ids_a", target: "writable"}},
			denyInsert:    "writable",
		},
		{
			name:          "target requires select permission",
			relationships: []insertRelationship{{source: "ids_a", target: "writable", array: true}},
			denySelect:    "writable",
		},
	}

	caps := schema.NewCapabilities(schema.KindPostgres, dialect.NewPostgresDialect())

	for _, tt := range tests { //nolint:paralleltest // Share the introspection pool across sequential cases.
		t.Run(tt.name, func(t *testing.T) {
			md := emptyInsertMetadata(tt.relationships)
			for i := range md.Tables {
				table := &md.Tables[i]
				if table.Table.Name == tt.denyInsert {
					table.InsertPermissions = nil
				}

				if table.Table.Name == tt.denySelect {
					table.SelectPermissions = nil
				}

				if tt.presetOnly && table.Table.Name == "likes" {
					table.InsertPermissions[0].Permission.Columns = nil
				}
			}

			for _, role := range []string{"admin", "writer"} { //nolint:paralleltest // Keep the matrix sequential.
				t.Run(role, func(t *testing.T) {
					wantTables := []string{"ids_a", "ids_b", "ids_c", "likes", "writable"}
					if role != "admin" {
						wantTables = slices.DeleteFunc(wantTables, func(name string) bool {
							return name == tt.denyInsert || name == tt.denySelect
						})
					}

					assertEmptyInsertRole(
						t,
						objects,
						md,
						caps,
						role,
						tt.relationships,
						wantTables,
						tt.denySelect,
					)
				})
			}
		})
	}
}

func assertEmptyInsertRole(
	t *testing.T, objects *introspection.Objects, md *metadata.DatabaseMetadata,
	caps schema.Capabilities, role string, relationships []insertRelationship,
	wantTables []string, denySelect string,
) {
	t.Helper()

	generated, err := schema.GenerateForRole(objects, role, md, caps)
	if err != nil {
		t.Fatalf("generate schema: %v", err)
	}

	_, sch, err := schemamerge.BuildValidatedSchema(generated, role)
	if err != nil {
		t.Fatalf("validate role schema: %v", err)
	}

	for i := range md.Tables {
		table := &md.Tables[i]
		name := table.Configuration.CustomName
		wantInsert := slices.Contains(wantTables, table.Table.Name)
		assertInsertSurfaces(t, sch, name, wantInsert, relationships, wantTables)

		if wantInsert && table.Table.Name != "writable" {
			wantFields := 0
			if role == "admin" && table.Table.Name == "likes" {
				wantFields++
			}

			for _, rel := range relationships {
				if rel.source == table.Table.Name && slices.Contains(wantTables, rel.target) {
					wantFields++
				}
			}

			if input := sch.Types[name+"_insert_input"]; input != nil &&
				len(input.Fields) != wantFields {
				t.Errorf(
					"%s has %d input fields, want %d",
					input.Name,
					len(input.Fields),
					wantFields,
				)
			}
		}

		if role == "writer" && table.Table.Name == denySelect {
			continue
		}

		assertIdentityReadSurfaces(t, sch, name)
	}
}

func emptyInsertMetadata(relationships []insertRelationship) *metadata.DatabaseMetadata {
	md := &metadata.DatabaseMetadata{Name: "default"}

	for _, name := range []string{"ids_a", "ids_b", "ids_c", "likes", "writable", "readonly_ids"} {
		columns := []string{"id"}
		if name == "likes" {
			columns = append(columns, "user_id")
		}

		if name == "writable" {
			columns = append(columns, "payload")
		}

		table := metadata.TableMetadata{
			Table:         metadata.TableSource{Schema: "public", Name: name},
			Configuration: metadata.TableConfiguration{CustomName: "custom_" + name},
			SelectPermissions: []metadata.SelectPermission{{
				Role: "writer",
				Permission: metadata.SelectPermissionConfig{
					Columns: columns, AllowAggregations: true,
				},
			}},
			InsertPermissions: []metadata.InsertPermission{{
				Role: "writer", Permission: metadata.InsertPermissionConfig{Columns: []string{}},
			}},
		}
		if name == "readonly_ids" {
			table.InsertPermissions = nil
		}

		if name == "writable" {
			table.InsertPermissions[0].Permission.Columns = columns
		}

		if name == "likes" {
			table.InsertPermissions[0].Permission.Columns = []string{"user_id"}
			table.InsertPermissions[0].Permission.Set = map[string]any{
				"user_id": "X-Hasura-User-Id",
			}
		}

		for _, rel := range relationships {
			if rel.source != name {
				continue
			}

			using := metadata.RelationshipUsing{ManualConfiguration: &metadata.ManualConfiguration{
				RemoteTable:   metadata.TableSource{Schema: "public", Name: rel.target},
				ColumnMapping: map[string]string{"id": "id"},
			}}
			if rel.array {
				table.ArrayRelationships = append(
					table.ArrayRelationships,
					metadata.ArrayRelationship{Name: "arr", Using: using},
				)
			} else {
				table.ObjectRelationships = append(
					table.ObjectRelationships,
					metadata.ObjectRelationship{Name: "obj", Using: using},
				)
			}
		}

		md.Tables = append(md.Tables, table)
	}

	return md
}

func assertInsertSurfaces(
	t *testing.T, sch *ast.Schema, name string, want bool,
	relationships []insertRelationship, wantTables []string,
) {
	t.Helper()

	for _, suffix := range []string{"_insert_input", "_on_conflict", "_constraint", "_update_column"} {
		if got := sch.Types[name+suffix] != nil; got != want {
			t.Errorf("type %s%s present = %v, want %v", name, suffix, got, want)
		}
	}

	for _, suffix := range []string{"", "_one"} {
		got := sch.Mutation != nil && sch.Mutation.Fields.ForName("insert_"+name+suffix) != nil
		if got != want {
			t.Errorf("insert_%s%s present = %v, want %v", name, suffix, got, want)
		}
	}

	input := sch.Types[name+"_insert_input"]
	if want && input == nil {
		return // The missing type was reported above.
	}

	if want && name != "custom_writable" && input.Fields.ForName("id") != nil {
		t.Errorf("%s_insert_input exposes ALWAYS identity", name)
	}

	assertInsertRelationships(t, sch, name, input, relationships, wantTables)
}

func assertInsertRelationships(
	t *testing.T, sch *ast.Schema, name string, input *ast.Definition,
	relationships []insertRelationship, wantTables []string,
) {
	t.Helper()

	wantObject, wantArray := false, false
	for _, rel := range relationships {
		if "custom_"+rel.target == name && slices.Contains(wantTables, rel.source) && input != nil {
			if rel.array {
				wantArray = true
			} else {
				wantObject = true
			}
		}

		if "custom_"+rel.source != name || input == nil {
			continue
		}

		relName := "obj"
		if rel.array {
			relName = "arr"
		}

		got := input.Fields.ForName(relName) != nil
		if expected := slices.Contains(wantTables, rel.target); got != expected {
			t.Errorf("%s_insert_input.%s present = %v, want %v", name, relName, got, expected)
		}
	}

	for suffix, expected := range map[string]bool{
		"_obj_rel_insert_input": wantObject, "_arr_rel_insert_input": wantArray,
	} {
		if got := sch.Types[name+suffix] != nil; got != expected {
			t.Errorf("type %s%s present = %v, want %v", name, suffix, got, expected)
		}
	}
}

func assertIdentityReadSurfaces(t *testing.T, sch *ast.Schema, name string) {
	t.Helper()

	for _, suffix := range []string{"", "_aggregate"} {
		if sch.Query.Fields.ForName(name+suffix) == nil {
			t.Errorf("missing query %s%s", name, suffix)
		}
	}

	if sch.Subscription.Fields.ForName(name+"_stream") == nil {
		t.Errorf("missing stream %s_stream", name)
	}

	for _, suffix := range []string{"", "_bool_exp", "_order_by", "_stream_cursor_value_input", "_max_fields", "_sum_fields"} {
		def := sch.Types[name+suffix]
		if def == nil || def.Fields.ForName("id") == nil {
			t.Errorf("missing readable field %s%s.id", name, suffix)
		}
	}
}
