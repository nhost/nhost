type mutationResponseTestCase struct {
	name          string
	table         string
	admin         bool
	insert        bool
	updateColumns []string
	preset        bool
	delete        bool
	otherMutation bool
	wantInsert    bool
	wantUpdate    bool
	wantDelete    bool
}

// Reuse one introspection result and pool across the permission matrix.
//
//nolint:paralleltest
func TestGenerateForRole_MutationResponseReachability(t *testing.T) {
	pool := testdb.NewPostgres(t, `
CREATE TABLE counters (id bigint GENERATED ALWAYS AS IDENTITY PRIMARY KEY);
CREATE TABLE computed (id integer GENERATED ALWAYS AS (1) STORED);
CREATE TABLE writable (id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, value integer DEFAULT 0);
CREATE VIEW readonly AS SELECT id FROM counters UNION ALL SELECT id FROM counters;`)
	connString := pool.Config().ConnConfig.ConnString()
	pool.Close()

	pgPool, err := postgres.Open(t.Context(), connString)
	if err != nil {
		t.Fatalf("open pool: %v", err)
	}

	pg := postgres.NewClient(pgPool)
	t.Cleanup(pg.Close)

	md := &metadata.DatabaseMetadata{Name: "default"}
	for _, name := range []string{"counters", "computed", "writable", "readonly"} {
		md.Tables = append(md.Tables, mutationResponseTable(name))
	}

	objects, err := pg.Introspect(t.Context(), md)
	if err != nil {
		t.Fatalf("introspect: %v", err)
	}

	tests := []mutationResponseTestCase{
		{name: "select only", table: "counters"},
		{name: "update only ALWAYS identity", table: "counters", updateColumns: []string{"id"}},
		{
			name:          "update only expression generated column",
			table:         "computed",
			updateColumns: []string{"id"},
		},
		{name: "empty update grant", table: "counters", updateColumns: []string{}},
		{
			name:          "preset only update",
			table:         "writable",
			updateColumns: []string{"value"},
			preset:        true,
		},
		{name: "default only insert", table: "counters", insert: true, wantInsert: true},
		{
			name:       "preset only insert",
			table:      "writable",
			insert:     true,
			preset:     true,
			wantInsert: true,
		},
		{
			name:          "writable update",
			table:         "writable",
			updateColumns: []string{"value"},
			wantUpdate:    true,
		},
		{name: "delete only", table: "counters", delete: true, wantDelete: true},
		{
			name: "pruned update with delete", table: "counters", updateColumns: []string{"id"},
			delete: true, wantDelete: true,
		},
		{
			name:          "pruned update with default insert",
			table:         "counters",
			updateColumns: []string{"id"},
			insert:        true,
			wantInsert:    true,
		},
		{
			name: "another table's mutation does not retain response", table: "counters",
			updateColumns: []string{"id"}, otherMutation: true,
		},
		{name: "read only insert", table: "readonly", insert: true},
		{name: "read only update", table: "readonly", updateColumns: []string{"id"}},
		{name: "read only delete", table: "readonly", delete: true},
		{
			name:       "admin keeps insert and delete",
			table:      "counters",
			admin:      true,
			wantInsert: true,
			wantDelete: true,
		},
		{name: "admin read only view", table: "readonly", admin: true},
	}
	caps := schema.NewCapabilities(schema.KindPostgres, dialect.NewPostgresDialect())

	for _, tt := range tests { //nolint:paralleltest // Keep the shared fixture matrix sequential.
		t.Run(tt.name, func(t *testing.T) {
			md := mutationResponseMetadata(tt)

			role := "writer"
			if tt.admin {
				role = "admin"
			}

			generated, err := schema.GenerateForRole(objects, role, md, caps)
			if err != nil {
				t.Fatalf("generate schema: %v", err)
			}

			_, sch, err := schemamerge.BuildValidatedSchema(generated, role)
			if err != nil {
				t.Fatalf("validate schema: %v", err)
			}

			name := "custom_" + tt.table
			assertMutationResponseSurfaces(
				t,
				sch,
				name,
				tt.wantInsert,
				tt.wantUpdate,
				tt.wantDelete,
			)

			if got := sch.Mutation != nil; got != (tt.wantInsert || tt.wantUpdate || tt.wantDelete || tt.otherMutation) {
				t.Errorf("mutation root present = %v", got)
			}

			if sch.Query.Fields.ForName(name) == nil ||
				sch.Types[name].Fields.ForName("id") == nil {
				t.Error("mutation gating removed the read API")
			}
		})
	}
}

func mutationResponseMetadata(tt mutationResponseTestCase) *metadata.DatabaseMetadata {
	table := mutationResponseTable(tt.table)
	if tt.insert {
		table.InsertPermissions = []metadata.InsertPermission{{
			Role: "writer", Permission: metadata.InsertPermissionConfig{Columns: []string{}},
		}}
		if tt.preset {
			table.InsertPermissions[0].Permission.Set = map[string]any{"value": 1}
		}
	}

	if tt.updateColumns != nil {
		table.UpdatePermissions = []metadata.UpdatePermission{{
			Role: "writer", Permission: metadata.UpdatePermissionConfig{Columns: tt.updateColumns},
		}}
		if tt.preset {
			table.UpdatePermissions[0].Permission.Set = map[string]any{"value": 1}
		}
	}

	if tt.delete {
		table.DeletePermissions = []metadata.DeletePermission{{Role: "writer"}}
	}

	md := &metadata.DatabaseMetadata{Name: "default"}
	if tt.otherMutation {
		other := mutationResponseTable("writable")
		other.DeletePermissions = []metadata.DeletePermission{{Role: "writer"}}
		md.Tables = append(md.Tables, other)
	}

	md.Tables = append(md.Tables, table)

	return md
}

func mutationResponseTable(name string) metadata.TableMetadata {
	return metadata.TableMetadata{
		Table:         metadata.TableSource{Schema: "public", Name: name},
		Configuration: metadata.TableConfiguration{CustomName: "custom_" + name},
		SelectPermissions: []metadata.SelectPermission{{
			Role: "writer", Permission: metadata.SelectPermissionConfig{Columns: []string{"id"}},
		}},
	}
}

func assertMutationResponseSurfaces(
	t *testing.T,
	sch *ast.Schema,
	name string,
	wantInsert, wantUpdate, wantDelete bool,
) {
	t.Helper()

	for field, want := range map[string]bool{
		"insert_" + name: wantInsert, "insert_" + name + "_one": wantInsert,
		"update_" + name: wantUpdate, "update_" + name + "_many": wantUpdate,
		"delete_" + name: wantDelete,
	} {
		if got := sch.Mutation != nil && sch.Mutation.Fields.ForName(field) != nil; got != want {
			t.Errorf("mutation %s present = %v, want %v", field, got, want)
		}
	}

	wantResponse := wantInsert || wantUpdate || wantDelete
	if got := sch.Types[name+"_mutation_response"] != nil; got != wantResponse {
		t.Errorf("type %s_mutation_response present = %v, want %v", name, got, wantResponse)
	}
}
