const defaultInsertDDL = `
CREATE TABLE bag (id bigint GENERATED ALWAYS AS IDENTITY PRIMARY KEY);
CREATE TABLE thing (
 id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 bag_id bigint REFERENCES bag(id),
 label text NOT NULL DEFAULT 'default'
);
CREATE TABLE upsert_defaults (
 id bigint GENERATED ALWAYS AS IDENTITY PRIMARY KEY,
 key text NOT NULL DEFAULT 'fixed' UNIQUE,
 label text NOT NULL DEFAULT 'new'
);
`

func defaultInsertMetadata() *metadata.DatabaseMetadata {
	md := &metadata.DatabaseMetadata{
		Name: "default", Kind: "postgres",
		Tables: []metadata.TableMetadata{
			{
				Table: metadata.TableSource{Schema: "public", Name: "bag"},
				ArrayRelationships: []metadata.ArrayRelationship{{
					Name: "things", Using: metadata.RelationshipUsing{
						ForeignKeyConstraint: &metadata.ForeignKeyConstraint{
							Columns: []string{"bag_id"},
							Table:   metadata.TableSource{Schema: "public", Name: "thing"},
						},
					},
				}},
			},
			{Table: metadata.TableSource{Schema: "public", Name: "thing"}},
			{Table: metadata.TableSource{Schema: "public", Name: "upsert_defaults"}},
		},
	}
	for i := 1; i < len(md.Tables); i++ {
		md.Tables[i].SelectPermissions = []metadata.SelectPermission{
			{
				Role:       "checked",
				Permission: metadata.SelectPermissionConfig{Columns: []string{"id", "label"}},
			},
		}
		md.Tables[i].InsertPermissions = []metadata.InsertPermission{{
			Role: "checked", Permission: metadata.InsertPermissionConfig{
				Columns: []string{"label"},
				Check:   map[string]any{"id": map[string]any{"_gt": "X-Hasura-Min-Id"}},
			},
		}}
		md.Tables[i].UpdatePermissions = []metadata.UpdatePermission{{
			Role: "checked", Permission: metadata.UpdatePermissionConfig{
				Columns: []string{"label"},
				Check:   map[string]any{"label": map[string]any{"_eq": "X-Hasura-Expected-Label"}},
			},
		}}
	}

	for _, role := range []string{"unchecked", "denied"} {
		check := map[string]any{}
		if role == "denied" {
			check["_not"] = map[string]any{}
		}

		md.Tables[1].SelectPermissions = append(
			md.Tables[1].SelectPermissions,
			metadata.SelectPermission{
				Role:       role,
				Permission: metadata.SelectPermissionConfig{Columns: []string{"id", "label"}},
			},
		)
		md.Tables[1].InsertPermissions = append(
			md.Tables[1].InsertPermissions,
			metadata.InsertPermission{
				Role: role,
				Permission: metadata.InsertPermissionConfig{
					Columns: []string{"label"},
					Check:   check,
				},
			},
		)
	}

	return md
}

// Every input here is representable by the current schema: thing has writable
// columns and bag has a relationship. Empty-input schema policy is independent
// of executing a row whose final SQL column set is empty.
//
//nolint:tparallel // Subtests reset the shared database; only the top-level fixture is parallel.
func TestDefaultInsertPostgresConnector(t *testing.T) {
	t.Parallel()

	seed := testdb.NewPostgres(t, defaultInsertDDL)
	connString := seed.Config().ConnConfig.ConnString()
	seed.Close()

	pool, err := postgres.Open(t.Context(), connString)
	if err != nil {
		t.Fatalf("Open: %v", err)
	}

	inc := metadata.NewInconsistencies()

	conn, err := csql.NewConnector(
		t.Context(),
		postgres.NewClient(pool),
		defaultInsertMetadata(),
		inc,
		nil,
	)
	if err != nil {
		pool.Close()
		t.Fatalf("NewConnector: %v", err)
	}

	t.Cleanup(conn.Close)

	if found := inc.Snapshot(); len(found) != 0 {
		t.Fatalf("unexpected inconsistencies: %+v", found)
	}

	schemas, err := conn.GetSchema()
	if err != nil {
		t.Fatalf("GetSchema: %v", err)
	}

	tests := defaultInsertCases()
	//nolint:paralleltest // Subtests reset the same tables and identity sequences.
	for _, tt := range tests {
		t.Run(tt.name, func(t *testing.T) {
			if err := pool.Exec(
				t.Context(),
				`TRUNCATE bag, thing, upsert_defaults RESTART IDENTITY CASCADE`,
			); err != nil {
				t.Fatalf("reset fixture: %v", err)
			}

			if tt.seed != "" {
				if err := pool.Exec(t.Context(), tt.seed); err != nil {
					t.Fatalf("seed fixture: %v", err)
				}
			}

			_, schema, err := schemamerge.BuildValidatedSchema(schemas[tt.role], tt.role)
			if err != nil {
				t.Fatalf("BuildValidatedSchema: %v", err)
			}

			doc, gqlErr := gqlparser.LoadQueryWithRules(schema, tt.query, nil)
			if gqlErr != nil {
				t.Fatalf("LoadQuery: %v", gqlErr)
			}

			result, err := conn.Execute(
				t.Context(),
				doc.Operations[0],
				doc.Fragments,
				nil,
				tt.role,
				map[string]any{
					"x-hasura-min-id":         tt.minID,
					"x-hasura-expected-label": tt.expectedLabel,
				},
				slog.New(slog.DiscardHandler),
			)
			assertDefaultInsertOutcome(t, result, err, tt)
			assertDefaultInsertStorage(t, pool, tt)
		})
	}
}

func assertDefaultInsertJSON(t *testing.T, result any, expected string) {
	t.Helper()

	raw, err := json.Marshal(result)
	if err != nil {
		t.Fatalf("encode result: %v", err)
	}

	var got, want any
	if err := json.Unmarshal(raw, &got); err != nil {
		t.Fatalf("decode result: %v", err)
	}

	if err := json.Unmarshal([]byte(expected), &want); err != nil {
		t.Fatalf("decode expectation: %v", err)
	}

	if diff := cmp.Diff(want, got); diff != "" {
		t.Errorf("result (-want +got):\n%s", diff)
	}
}

type defaultInsertCase struct {
	name, role, query, seed, want string
	minID, expectedLabel          string
	wantDenied                    bool
	counts                        [3]int
	storedLabel                   string
}

func defaultInsertCases() []defaultInsertCase {
	return []defaultInsertCase{
		{
			name: "single default row", role: "admin",
			query: `mutation { result: insert_thing_one(object: {}) { id label bag_id } }`,
			want:  `{"id":1,"label":"default","bag_id":null}`, counts: [3]int{0, 1, 0},
		},
		{
			name:   "multiple default rows",
			role:   "admin",
			query:  `mutation { result: insert_thing(objects: [{}, {}]) { affected_rows returning { id label } } }`,
			want:   `{"affected_rows":2,"returning":[{"id":1,"label":"default"},{"id":2,"label":"default"}]}`,
			counts: [3]int{0, 2, 0},
		},
		{
			name:   "pre-check default rows",
			role:   "unchecked",
			query:  `mutation { result: insert_thing(objects: [{}, {}]) { affected_rows returning { id label } } }`,
			want:   `{"affected_rows":2,"returning":[{"id":1,"label":"default"},{"id":2,"label":"default"}]}`,
			counts: [3]int{0, 2, 0},
		},
		{
			name: "pre-check denied", role: "denied", wantDenied: true,
			query: `mutation { result: insert_thing(objects: [{}, {}]) { affected_rows } }`,
		},
		{
			name:   "identity-dependent post-check",
			role:   "checked",
			minID:  "0",
			query:  `mutation { result: insert_thing(objects: [{}, {}]) { affected_rows returning { id label } } }`,
			want:   `{"affected_rows":2,"returning":[{"id":1,"label":"default"},{"id":2,"label":"default"}]}`,
			counts: [3]int{0, 2, 0},
		},
		{
			name: "post-check rollback", role: "checked", minID: "1000000", wantDenied: true,
			query: `mutation { result: insert_thing(objects: [{}, {}]) { affected_rows } }`,
		},
		{
			name: "relationship-only parent and array defaults",
			role: "admin",
			query: `mutation { result: insert_bag_one(object: {things: {data: [{label: "a"}, {}]}}) {
			 id things(order_by: {id: asc}) { id bag_id label }
			} }`,
			want:   `{"id":1,"things":[{"id":1,"bag_id":1,"label":"a"},{"id":2,"bag_id":1,"label":"default"}]}`,
			counts: [3]int{1, 2, 0},
		},
		{
			name: "multiple default parents", role: "admin",
			query: `mutation { result: insert_bag(objects: [
			 {things: {data: [{}]}}, {things: {data: [{}, {}]}}
			]) { affected_rows returning { id things(order_by: {id: asc}) { id bag_id label } } } }`,
			want: `{"affected_rows":5,"returning":[
			 {"id":1,"things":[{"id":1,"bag_id":1,"label":"default"}]},
			 {"id":2,"things":[{"id":2,"bag_id":2,"label":"default"},{"id":3,"bag_id":2,"label":"default"}]}
			]}`, counts: [3]int{2, 3, 0},
		},
		{
			name: "default upsert insert", role: "admin",
			query: `mutation { result: insert_upsert_defaults_one(object: {},
			 on_conflict: {constraint: upsert_defaults_key_key, update_columns: []}) { id label } }`,
			want: `{"id":1,"label":"new"}`, counts: [3]int{0, 0, 1}, storedLabel: "new",
		},
		{
			name: "default upsert do nothing", role: "admin",
			seed: `INSERT INTO upsert_defaults (label) VALUES ('old')`,
			query: `mutation { result: insert_upsert_defaults(objects: [{}, {}],
			 on_conflict: {constraint: upsert_defaults_key_key, update_columns: []}) { affected_rows returning { id } } }`,
			want: `{"affected_rows":0,"returning":[]}`, counts: [3]int{0, 0, 1}, storedLabel: "old",
		},
		{
			name:          "default upsert post-check insert",
			role:          "checked",
			minID:         "0",
			expectedLabel: "new",
			query: `mutation { result: insert_upsert_defaults_one(object: {},
			 on_conflict: {constraint: upsert_defaults_key_key, update_columns: [label]}) { id label } }`,
			want:        `{"id":1,"label":"new"}`,
			counts:      [3]int{0, 0, 1},
			storedLabel: "new",
		},
		{
			name:          "default upsert checks only update branch",
			role:          "checked",
			minID:         "1000000",
			expectedLabel: "new",
			seed:          `INSERT INTO upsert_defaults (label) VALUES ('old')`,
			query: `mutation { result: insert_upsert_defaults_one(object: {},
			 on_conflict: {constraint: upsert_defaults_key_key, update_columns: [label]}) { id label } }`,
			want:        `{"id":1,"label":"new"}`,
			counts:      [3]int{0, 0, 1},
			storedLabel: "new",
		},
		{
			name:          "default upsert update-check rollback",
			role:          "checked",
			minID:         "0",
			expectedLabel: "blocked",
			seed:          `INSERT INTO upsert_defaults (label) VALUES ('old')`,
			wantDenied:    true,
			query: `mutation { result: insert_upsert_defaults_one(object: {},
			 on_conflict: {constraint: upsert_defaults_key_key, update_columns: [label]}) { id label } }`,
			counts:      [3]int{0, 0, 1},
			storedLabel: "old",
		},
	}
}

func assertDefaultInsertOutcome(
	t *testing.T,
	result map[string]any,
	err error,
	tt defaultInsertCase,
) {
	t.Helper()

	if tt.wantDenied {
		pgErr, ok := errors.AsType[*pgconn.PgError](err)
		if !ok || pgErr.Code != "ZZ901" {
			t.Fatalf("Execute error = %v, want permission denial ZZ901", err)
		}

		return
	}

	if err != nil {
		t.Fatalf("Execute: %v", err)
	}

	assertDefaultInsertJSON(t, result["result"], tt.want)
}

func assertDefaultInsertStorage(t *testing.T, pool postgres.Querier, tt defaultInsertCase) {
	t.Helper()

	var counts [3]int
	if err := pool.QueryRow(t.Context(), `SELECT (SELECT count(*) FROM bag),
	 (SELECT count(*) FROM thing), (SELECT count(*) FROM upsert_defaults)`).Scan(
		&counts[0], &counts[1], &counts[2]); err != nil {
		t.Fatalf("count stored rows: %v", err)
	}

	if counts != tt.counts {
		t.Errorf("stored row counts = %v, want %v", counts, tt.counts)
	}

	if tt.storedLabel != "" {
		var label string
		if err := pool.QueryRow(t.Context(), `SELECT label FROM upsert_defaults`).
			Scan(&label); err != nil {
			t.Fatalf("read stored upsert: %v", err)
		}

		if label != tt.storedLabel {
			t.Errorf("stored upsert label = %q, want %q", label, tt.storedLabel)
		}
	}
}
