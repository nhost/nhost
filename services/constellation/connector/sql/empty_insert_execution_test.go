const emptyInsertDDL = `
CREATE TABLE solo (id bigint GENERATED ALWAYS AS IDENTITY PRIMARY KEY);
CREATE TABLE likes (id bigint GENERATED ALWAYS AS IDENTITY PRIMARY KEY, user_id text NOT NULL);
CREATE TABLE entries (
 id bigint GENERATED ALWAYS AS IDENTITY PRIMARY KEY,
 solo_id bigint REFERENCES solo(id),
 label text NOT NULL DEFAULT 'default'
);
CREATE TABLE tags (id bigint GENERATED ALWAYS AS IDENTITY PRIMARY KEY, entry_id bigint REFERENCES entries(id));
CREATE TABLE by_default (id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY);
CREATE TABLE serials (id bigserial PRIMARY KEY);
`

func emptyExecutionMetadata() *metadata.DatabaseMetadata {
	md := &metadata.DatabaseMetadata{Name: "default", Kind: "postgres"}
	for _, name := range []string{"solo", "likes", "entries", "tags", "by_default", "serials"} {
		columns := []string{}
		switch name {
		case "likes":
			columns = []string{"user_id"}
		case "entries":
			columns = []string{"label"}
		case "by_default", "serials":
			columns = []string{"id"}
		}

		table := metadata.TableMetadata{Table: metadata.TableSource{Schema: "public", Name: name}}
		for _, role := range []string{"writer", "preset_empty"} {
			permission := metadata.InsertPermissionConfig{Columns: columns, Check: map[string]any{}}
			if name == "likes" {
				permission.Set = map[string]any{"user_id": "X-Hasura-User-Id"}

				permission.Check = map[string]any{
					"user_id": map[string]any{"_eq": "X-Hasura-User-Id"},
				}
				if role == "preset_empty" {
					permission.Columns = []string{}
				}
			}

			if name == "solo" || name == "tags" {
				permission.Check = map[string]any{"id": map[string]any{"_gt": "X-Hasura-Min-Id"}}
			}

			table.SelectPermissions = append(table.SelectPermissions, metadata.SelectPermission{
				Role: role, Permission: metadata.SelectPermissionConfig{Columns: []string{"*"}},
			})
			table.InsertPermissions = append(table.InsertPermissions, metadata.InsertPermission{
				Role: role, Permission: permission,
			})
		}

		if name == "entries" {
			table.ObjectRelationships = []metadata.ObjectRelationship{{
				Name: "solo", Using: metadata.RelationshipUsing{
					ForeignKeyColumns: []string{"solo_id"},
				},
			}}
			table.ArrayRelationships = []metadata.ArrayRelationship{{
				Name: "tags", Using: metadata.RelationshipUsing{
					ForeignKeyConstraint: &metadata.ForeignKeyConstraint{
						Columns: []string{
							"entry_id",
						},
						Table: metadata.TableSource{Schema: "public", Name: "tags"},
					},
				},
			}}
		}

		md.Tables = append(md.Tables, table)
	}

	return md
}

// Reuse one pool; reset rows and sequences between sequential execution cases.
//
//nolint:paralleltest
func TestEmptyInsertPostgresConnector(t *testing.T) {
	seed := testdb.NewPostgres(t, emptyInsertDDL)
	connString := seed.Config().ConnConfig.ConnString()
	seed.Close()

	pool, err := postgres.Open(t.Context(), connString)
	if err != nil {
		t.Fatalf("Open: %v", err)
	}

	inc := metadata.NewInconsistencies()
	md := emptyExecutionMetadata()

	conn, err := csql.NewConnector(t.Context(), postgres.NewClient(pool), md, inc, nil)
	if err != nil {
		pool.Close()
		t.Fatalf("NewConnector: %v", err)
	}

	t.Cleanup(conn.Close)

	logger := slog.New(slog.DiscardHandler)

	composed := composer.New(
		map[string]composer.SchemaProvider{"default": conn},
		&metadata.Metadata{
			Databases: []metadata.DatabaseMetadata{*md},
		},
		inc,
	).Compose(t.Context(), logger)
	if found := inc.Snapshot(); len(found) != 0 {
		t.Fatalf("unexpected inconsistencies: %+v", found)
	}

	for _, role := range []string{"admin", "writer", "preset_empty"} {
		schema := composed.ValidatedSchemas[role]
		if schema == nil {
			t.Fatalf("composition dropped role %s", role)
		}

		assertEmptyInsertIntrospection(t, schema, role)

		if got := composed.FieldToConnector[schemamerge.FieldKey(ast.Mutation, "insert_solo_one")]; got != "default" {
			t.Fatalf("insert routing = %q", got)
		}

		if fields := composed.SchemaDocs[role].Definitions.ForName(
			"solo_insert_input",
		).Fields; len(
			fields,
		) != 0 {
			t.Fatal("schema document contains a placeholder")
		}

		assertEmptyInsertHiddenFields(t, schema, role)
	}

	for _, tt := range emptyExecutionCases() { //nolint:paralleltest // Shared rows and identity sequences.
		t.Run(tt.name, func(t *testing.T) {
			runEmptyInsertCase(t, conn, pool, composed.ValidatedSchemas[tt.role], tt)
		})
	}
}

func runEmptyInsertCase(
	t *testing.T,
	conn *csql.Connector,
	pool postgres.Querier,
	schema *ast.Schema,
	tt emptyExecutionCase,
) {
	t.Helper()

	if err := pool.Exec(
		t.Context(),
		`TRUNCATE solo, likes, entries, tags, by_default, serials RESTART IDENTITY CASCADE`,
	); err != nil {
		t.Fatalf("reset fixture: %v", err)
	}

	doc, errs := gqlparser.LoadQueryWithRules(schema, tt.query, nil)
	if errs != nil {
		t.Fatalf("LoadQuery: %v", errs)
	}

	variables, err := validator.VariableValues(schema, doc.Operations[0], tt.variables)
	if err != nil {
		t.Fatalf("VariableValues: %v", err)
	}

	minID := "0"
	if tt.denied {
		minID = "1000000"
	}

	result, err := conn.Execute(
		t.Context(),
		doc.Operations[0],
		doc.Fragments,
		variables,
		tt.role,
		map[string]any{"x-hasura-user-id": "u1", "x-hasura-min-id": minID},
		slog.New(slog.DiscardHandler),
	)
	if tt.denied {
		pgErr, ok := errors.AsType[*pgconn.PgError](err)
		if !ok || pgErr.Code != "ZZ901" {
			t.Fatalf("Execute error = %v, want permission denial ZZ901", err)
		}
	} else {
		if err != nil {
			t.Fatalf("Execute: %v", err)
		}

		assertDefaultInsertJSON(t, result["result"], tt.want)
	}

	var counts [4]int
	if err := pool.QueryRow(t.Context(), `SELECT (SELECT count(*) FROM solo), (SELECT count(*) FROM likes),
	 (SELECT count(*) FROM entries), (SELECT count(*) FROM tags)`).
		Scan(
			&counts[0], &counts[1], &counts[2], &counts[3]); err != nil {
		t.Fatalf("stored counts: %v", err)
	}

	if counts != tt.counts {
		t.Errorf("stored counts = %v, want %v", counts, tt.counts)
	}
}

type emptyExecutionCase struct {
	name, role, query, want string
	variables               map[string]any
	denied                  bool
	counts                  [4]int
}

func emptyExecutionCases() []emptyExecutionCase {
	cases := []emptyExecutionCase{}
	for _, role := range []string{"admin", "writer", "preset_empty"} {
		cases = append(cases,
			emptyExecutionCase{
				name:   role + " identity default",
				role:   role,
				query:  `mutation { result: insert_solo_one(object: {}) { id } }`,
				want:   `{"id":1}`,
				counts: [4]int{1},
			},
			emptyExecutionCase{
				name:   role + " bulk identity defaults",
				role:   role,
				query:  `mutation { result: insert_solo(objects: [{}, {}]) { affected_rows returning { id } } }`,
				want:   `{"affected_rows":2,"returning":[{"id":1},{"id":2}]}`,
				counts: [4]int{2},
			},
		)
	}

	for _, role := range []string{"writer", "preset_empty"} {
		cases = append(cases,
			emptyExecutionCase{
				name: role + " preset", role: role,
				query: `mutation { result: insert_likes_one(object: {}) { id user_id } }`,
				want:  `{"id":1,"user_id":"u1"}`, counts: [4]int{0, 1},
			},
			emptyExecutionCase{
				name:      role + " bulk preset variables",
				role:      role,
				query:     `mutation($objects: [likes_insert_input!]!) { result: insert_likes(objects: $objects) { affected_rows returning { id user_id } } }`,
				variables: map[string]any{"objects": []any{map[string]any{}, map[string]any{}}},
				want:      `{"affected_rows":2,"returning":[{"id":1,"user_id":"u1"},{"id":2,"user_id":"u1"}]}`,
				counts:    [4]int{0, 2},
			},
		)
	}

	return append(cases,
		emptyExecutionCase{
			name:   "variable default empty object",
			role:   "writer",
			query:  `mutation($object: solo_insert_input! = {}) { result: insert_solo_one(object: $object) { id } }`,
			want:   `{"id":1}`,
			counts: [4]int{1},
		},
		emptyExecutionCase{
			name: "empty input on conflict", role: "writer",
			query: `mutation { result: insert_solo(objects: [{}, {}],
			 on_conflict: {constraint: solo_pkey, update_columns: []}) { affected_rows returning { id } } }`,
			want: `{"affected_rows":2,"returning":[{"id":1},{"id":2}]}`, counts: [4]int{2},
		},
		emptyExecutionCase{
			name: "bulk default rollback", role: "writer", denied: true,
			query: `mutation { result: insert_solo(objects: [{}, {}]) { affected_rows } }`,
		},
		emptyExecutionCase{
			name: "nested empty object and array with foreign keys",
			role: "writer",
			query: `mutation { result: insert_entries_one(object: {solo: {data: {}}, tags: {data: [{}, {}]}}) {
			 id solo_id label solo { id } tags(order_by: {id: asc}) { id entry_id }
			} }`,
			want:   `{"id":1,"solo_id":1,"label":"default","solo":{"id":1},"tags":[{"id":1,"entry_id":1},{"id":2,"entry_id":1}]}`,
			counts: [4]int{1, 0, 1, 2},
		},
		emptyExecutionCase{
			name: "nested object post-check rollback", role: "writer", denied: true,
			query: `mutation { result: insert_entries_one(object: {solo: {data: {}}}) { id } }`,
		},
		emptyExecutionCase{
			name:   "nested array post-check rollback",
			role:   "writer",
			denied: true,
			query:  `mutation { result: insert_entries_one(object: {tags: {data: [{}, {}]}}) { id } }`,
		},
		emptyExecutionCase{
			name:  "by default explicit value",
			role:  "writer",
			query: `mutation { result: insert_by_default_one(object: {id: 42}) { id } }`,
			want:  `{"id":42}`,
		},
		emptyExecutionCase{
			name:  "serial explicit value",
			role:  "writer",
			query: `mutation { result: insert_serials_one(object: {id: 43}) { id } }`,
			want:  `{"id":43}`,
		},
	)
}

func assertEmptyInsertIntrospection(t *testing.T, schema *ast.Schema, role string) {
	t.Helper()

	for _, name := range []string{"solo", "likes", "tags"} {
		if role == "admin" && name != "solo" {
			continue
		}

		doc, errs := gqlparser.LoadQueryWithRules(schema,
			`{ __type(name: "`+name+`_insert_input") { kind inputFields { name } } }`, nil)
		if errs != nil {
			t.Fatalf("introspection query: %v", errs)
		}

		got := gqlintrospection.Execute(schema, doc.Operations[0], doc)
		assertDefaultInsertJSON(t, got, `{"__type":{"kind":"INPUT_OBJECT","inputFields":[]}}`)

		for _, suffix := range []string{"", "_one"} {
			if schema.Mutation.Fields.ForName("insert_"+name+suffix) == nil {
				t.Errorf("missing %s insert_%s%s", role, name, suffix)
			}
		}
	}
}

func assertEmptyInsertHiddenFields(t *testing.T, schema *ast.Schema, role string) {
	t.Helper()

	queries := []string{`mutation { insert_solo_one(object: {id: 42}) { id } }`}
	if role != "admin" {
		queries = append(queries,
			`mutation { insert_likes_one(object: {user_id: "override"}) { id } }`,
			`mutation { insert_likes_one(object: {id: 42}) { id } }`,
			`mutation { insert_tags_one(object: {entry_id: 42}) { id } }`)
	}

	for _, query := range queries {
		if _, errs := gqlparser.LoadQueryWithRules(schema, query, nil); errs == nil {
			t.Errorf("%s accepted hidden field: %s", role, query)
		}
	}

	if role == "admin" {
		return
	}

	doc, errs := gqlparser.LoadQueryWithRules(schema,
		`mutation($object: likes_insert_input!) { insert_likes_one(object: $object) { id } }`, nil)
	if errs != nil {
		t.Fatalf("variable query: %v", errs)
	}

	for _, field := range []string{"id", "user_id", "_constellation_validation_only"} {
		_, err := validator.VariableValues(schema, doc.Operations[0],
			map[string]any{"object": map[string]any{field: "override"}})
		if err == nil {
			t.Errorf("%s accepted hidden variable field %s", role, field)
		}
	}
}
